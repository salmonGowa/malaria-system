export const SIM_DICTIONARIES = { en, sw };

export function useSimText() {
  const { language } = useLanguage();
  return useMemo(() => {
    const dict: Record<SimKey, string> = language === "sw" ? sw : en;
    return (key: SimKey, vars?: Record<string, string | number>) => {
      let value = dict[key] ?? en[key] ?? key;
      if (vars) for (const [name, v] of Object.entries(vars)) value = value.split(`{{${name}}}`).join(String(v));
      return value;
    };
  }, [language]);
}
