import pytest

from app.upload_simulation import UploadValidationError, MIN_ROWS, parse_csv, simulate_upload


def _csv(rows, header="date,confirmed_cases,rainfall_mm"):
    return (header + "\n" + "\n".join(rows)).encode("utf-8")


def _valid_rows(n=8):
    return [f"2026-{i + 1:02d}-01,{100 + i * 10},{40 + i * 5}" for i in range(n)]


class TestParseCsv:
    def test_parses_and_returns_expected_fields(self):
        raw = _csv(_valid_rows(MIN_ROWS))
        rows = parse_csv(raw)
        assert rows[0]["date"].isoformat() == "2026-01-01"
        assert rows[0]["confirmed_cases"] == 100.0
        assert rows[0]["rainfall_mm"] == 40.0

    def test_rejects_too_few_rows(self):
        raw = _csv(_valid_rows(MIN_ROWS - 1))
        with pytest.raises(UploadValidationError, match="at least"):
            parse_csv(raw)

    def test_accepts_exactly_the_minimum(self):
        raw = _csv(_valid_rows(MIN_ROWS))
        rows = parse_csv(raw)
        assert len(rows) == MIN_ROWS

    def test_sorts_out_of_order_rows_chronologically(self):
        rows_text = _valid_rows(MIN_ROWS)
        shuffled = [rows_text[2], rows_text[0], *rows_text[1:2], *rows_text[3:]]
        rows = parse_csv(_csv(shuffled))
        dates = [r["date"] for r in rows]
        assert dates == sorted(dates)

    def test_missing_required_column_is_rejected(self):
        raw = b"date,rainfall_mm\n2026-01-01,40\n2026-02-01,50\n"
        with pytest.raises(UploadValidationError, match="confirmed_cases"):
            parse_csv(raw)

    def test_non_numeric_cases_is_rejected_with_line_number(self):
        rows_text = _valid_rows(MIN_ROWS)
        rows_text[2] = "2026-03-01,not-a-number,50"
        with pytest.raises(UploadValidationError, match="Line 4"):  # header + 3 preceding rows
            parse_csv(_csv(rows_text))

    def test_negative_cases_is_rejected(self):
        rows_text = _valid_rows(MIN_ROWS)
        rows_text[0] = "2026-01-01,-5,40"
        with pytest.raises(UploadValidationError, match="negative"):
            parse_csv(_csv(rows_text))

    def test_unrecognised_date_format_is_rejected(self):
        rows_text = _valid_rows(MIN_ROWS)
        rows_text[0] = "01/01/2026,100,40"
        with pytest.raises(UploadValidationError, match="unrecognised date"):
            parse_csv(_csv(rows_text))

    def test_rainfall_column_is_optional(self):
        header = "date,confirmed_cases"
        rows_text = [f"2026-{i + 1:02d}-01,{100 + i * 10}" for i in range(MIN_ROWS)]
        rows = parse_csv(_csv(rows_text, header=header))
        assert all(r["rainfall_mm"] is None for r in rows)

    def test_blank_trailing_line_is_ignored_not_a_parse_error(self):
        raw = _csv(_valid_rows(MIN_ROWS)) + b"\n"  # trailing newline -> one blank DictReader row
        rows = parse_csv(raw)
        assert len(rows) == MIN_ROWS


class TestSimulateUpload:
    def test_returns_a_fit_and_a_forecast_extension(self):
        rows = parse_csv(_csv(_valid_rows(10)))
        result = simulate_upload(rows, population=500_000, horizon_months=4)

        assert result["rows_used"] == 10
        assert result["used_rainfall"] is True
        assert set(result["fitted_params"].keys()) == {"beta0", "k", "reporting_fraction"}
        assert result["fit_relative_error"] >= 0

        uploaded_points = [p for p in result["series"] if p["actual"] is not None]
        forecast_points = [p for p in result["series"] if p["predicted"] is not None]
        assert len(uploaded_points) == 10
        assert len(forecast_points) == 4
        # Uploaded points carry a fitted value alongside actual; forecast
        # points carry only predicted (nothing "actual" to compare against yet).
        assert all(p["fitted"] is not None for p in uploaded_points)
        assert all(p["actual"] is None for p in forecast_points)

    def test_no_warning_when_the_data_is_genuinely_seir_shaped(self):
        # Data generated BY the model itself (same self-consistency trick as
        # test_compartmental.py) — a real single epidemic wave, which a plain
        # SEIR should fit cleanly with no "doesn't track well" warning.
        from app.compartmental import SEIRParams, initial_state_for, simulate_series

        rainfall = [60, 80, 150, 220, 190, 70, 40, 50, 90, 160]
        true_params = SEIRParams(beta0=0.4, k=1.2, reporting_fraction=0.02)
        cases = simulate_series(true_params, initial_state_for(500_000), rainfall)
        rows_text = [f"2026-{i + 1:02d}-01,{c:.1f},{r}" for i, (c, r) in enumerate(zip(cases, rainfall))]
        rows = parse_csv(_csv(rows_text))

        result = simulate_upload(rows, population=500_000, horizon_months=2)

        assert result["fit_relative_error"] < 0.05
        assert result["warnings"] == []

    def test_warns_when_no_rainfall_column(self):
        header = "date,confirmed_cases"
        rows_text = [f"2026-{i + 1:02d}-01,{100 + i * 10}" for i in range(MIN_ROWS)]
        rows = parse_csv(_csv(rows_text, header=header))
        result = simulate_upload(rows, population=500_000, horizon_months=3)
        assert result["used_rainfall"] is False
        assert any("No rainfall_mm" in w for w in result["warnings"])

    def test_warns_when_the_series_has_more_than_one_wave(self):
        # Up, down, up again, down again — a plain SEIR (permanent immunity,
        # no reinfection) structurally can't reproduce that in one fit.
        multi_wave = [4200, 4500, 5100, 6200, 5800, 4100, 3200, 3400, 3900, 4600, 5200, 4800]
        rainfall = [60, 80, 150, 220, 190, 70, 40, 50, 90, 160, 180, 110]
        rows_text = [f"2026-{i + 1:02d}-01,{c},{r}" for i, (c, r) in enumerate(zip(multi_wave, rainfall))]
        rows = parse_csv(_csv(rows_text))

        result = simulate_upload(rows, population=800_000, horizon_months=3)

        assert result["fit_relative_error"] > 0.5
        assert any("more than one seasonal wave" in w for w in result["warnings"])

    def test_forecast_values_are_finite_and_bounded_by_population(self):
        rows = parse_csv(_csv(_valid_rows(8)))
        result = simulate_upload(rows, population=200_000, horizon_months=6)
        for p in result["series"]:
            for key in ("actual", "fitted", "predicted"):
                if p[key] is not None:
                    assert 0 <= p[key] < 200_000
